'use client'

import { useEffect, useRef } from 'react'
import copy from './record-room/copy.json'

/*
 * How HataD works: a record room, played by the scroll.
 *
 * The words are rendered here, on the server, so they read before any script runs and are
 * what a crawler sees. The drawing is not: it is two SVG layers of about five thousand parts,
 * so it lives as static files in /public/figures/record-room and is fetched only as the section
 * nears the screen, then animated by live.js. Keeping it out of the bundle is deliberate: a
 * multi-megabyte string literal in the source once made every cold start take minutes.
 *
 * Both the drawing and the animation are generated by record-room.mjs (the figure's build
 * script); copy.json comes from the same run, so the counts on the page and in the drawing are
 * the same number. Regenerate them together; never edit one by hand.
 *
 * Everything the section styles is nested under .rr in record-room.css, so nothing reaches the
 * rest of the site. The class names and data attributes below are the contract live.js reads.
 */

const ASSETS = '/figures/record-room'

type Mount = (root: HTMLElement) => () => void

export function RecordRoom() {
  const rootRef = useRef<HTMLElement>(null)
  const stageRef = useRef<HTMLDivElement>(null)

  useEffect(() => {
    const root = rootRef.current
    const stage = stageRef.current
    if (!root || !stage) return
    let cancelled = false
    let cleanup: (() => void) | undefined

    const start = async () => {
      try {
        const res = await fetch(`${ASSETS}/scene.html`)
        if (!res.ok) throw new Error(`scene.html answered ${res.status}`)
        const scene = await res.text()
        if (cancelled) return
        stage.innerHTML = scene
        const url = `${ASSETS}/live.js`
        const mod: { mount: Mount } = await import(/* webpackIgnore: true */ /* turbopackIgnore: true */ url)
        if (cancelled) return
        cleanup = mod.mount(root)
      } catch (err) {
        // The words are already on the page; the section reads without its drawing.
        console.error('[RecordRoom] the drawing did not load', err)
      }
    }

    // Start a screen and a half early, so the room is drawn by the time it scrolls in.
    const io = new IntersectionObserver(
      (entries) => {
        if (entries.some((e) => e.isIntersecting)) {
          io.disconnect()
          void start()
        }
      },
      { rootMargin: '150% 0px' },
    )
    io.observe(root)

    return () => {
      cancelled = true
      io.disconnect()
      cleanup?.()
    }
  }, [])

  const total = copy.beats.length

  /*
   * Full bleed: the drawing fills the pinned screen and the words sit on it, the headline
   * bottom-left, the chapters down the right edge, the counter card bottom-right. The order
   * below is the reading order for a screen reader; the stylesheet places them.
   */
  return (
    <section ref={rootRef} className="rr" aria-label="How HataD works">
      <link rel="stylesheet" href={`${ASSETS}/record-room.css`} precedence="default" />
      <div className="iso" data-theme="light">
        <div className="track">
          <div className="stage">
            <div className="bare">
              {/* Filled by the effect above. React renders no children here, so it never
                  reconciles the drawing that live.js moves. */}
              <div ref={stageRef} className="iso-stage" />
            </div>
            {/* The page's second chapter: numbered in the page's own sequence, 01 the hero */}
            <p className="kick">
              <b>02</b>
              <i aria-hidden />
              <span>How HataD works · {total} steps</span>
            </p>
            <div className="copy">
              <div className="says">
                {copy.beats.map((beat, i) => {
                  let word = 0
                  return (
                    <div key={beat.tag} className={i === 0 ? 'say on' : 'say'} data-step={i}>
                      <h2>
                        {beat.words.map((w, j) => (
                          <span key={j}>
                            {j > 0 && ' '}
                            <span className="w">
                              <span
                                className={w.em ? 'e' : undefined}
                                style={{ '--i': word++ } as React.CSSProperties}
                              >
                                {w.w}
                              </span>
                            </span>
                          </span>
                        ))}
                      </h2>
                      <p>{beat.sub}</p>
                    </div>
                  )
                })}
              </div>
              <div className="reads" data-reads aria-hidden>
                <p>
                  <span className="lab">Reads</span>
                  {copy.reads.join(' · ')}
                </p>
                <p>
                  <span className="lab">For</span>
                  {copy.for.join(' · ')}
                </p>
              </div>
            </div>
            <nav className="chapters" aria-label="Chapters">
              <ol>
                {copy.beats.map((beat, i) => (
                  <li key={beat.tag}>
                    <button
                      type="button"
                      data-chapter={i}
                      className={i === 0 ? 'on' : undefined}
                      aria-label={`Chapter ${i + 1} of ${total}: ${beat.tag}`}
                    >
                      <span className="no">{String(i + 1).padStart(2, '0')}</span>
                      <span className="ln">
                        <b />
                      </span>
                      <span className="nm">{beat.tag}</span>
                    </button>
                  </li>
                ))}
              </ol>
              <button type="button" className="play" data-play>
                ▶ Play
              </button>
            </nav>
            <aside className="inst" aria-hidden>
              <div className="metric">
                <span className="mlab" data-mlab>
                  bundles in the room · none indexed
                </span>
                <span className="mbig" data-mbig>
                  {copy.bundles}
                </span>
                <span className="mof" data-mof />
              </div>
              <p className="live" data-readout>
                record room
              </p>
              <div className="bar">
                <b />
              </div>
            </aside>
            <p className="sr" aria-live="polite" data-announce />
          </div>
        </div>
      </div>
    </section>
  )
}
